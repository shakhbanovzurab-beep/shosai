// Флаги Chromium для съёмки и записи: одна среда браузера на оба прогона.

/**
 * Микрофон — поддельное устройство Chromium без запроса разрешения: запись
 * и распознавание идут так же, как у пользователя, разрешившего доступ.
 *
 * Частичная растеризация выключена. Действие состояния меняет уже нарисованную
 * страницу, и браузер перерисовывал бы лишь изменённые прямоугольники внутри
 * готовых плиток; их границы зависят от того, как изменения разложились по
 * кадрам, и сглаживание на краях расходилось на единицы яркости от прогона к
 * прогону. Изменённая плитка рисуется целиком — кадр повторяется.
 *
 * Субпиксельное (LCD) сглаживание текста выключено. Chromium включает его, только
 * когда текст рисуется без отдельного композитного слоя; блоки с анимацией
 * появления выносятся в слой и обратно в зависимости от тайминга, и один и тот
 * же текст выходил то цветным, то серым. Серое сглаживание — всегда.
 */
export const CHROMIUM_ARGS: readonly string[] = [
  "--use-fake-ui-for-media-stream",
  "--use-fake-device-for-media-stream",
  "--disable-partial-raster",
  "--disable-lcd-text",
];
